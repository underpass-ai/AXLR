#!/usr/bin/env python3
"""Write catalog/tools/personal/wordle_helper/words5.txt: the small list of five-letter English
words the tool bundles when no word list is given, fetched once from SCOWL / the English Speller
Database (ESDB) by Kevin Atkinson (this generator uses the network; the tool never does).

Source: https://app.aspell.net/create (ESDB, https://wordlist.aspell.net), size 35 ("small"),
US spelling, max_variant=0 requested, diacritics stripped. Fetched 2026-10-18.
Licence: the ESDB permissive licence (MIT-like, quoted in full at the top of the data file):
"Permission to use, copy, modify, distribute, and sell any part of the English Speller Database
(ESDB, previously known as SCOWLv2), or word lists created from it, is hereby granted without
fee, provided that the above copyright notice appears in all copies and that both the above
copyright notice and this notice appear in supporting documentation." The notice is copied
into the data file and the tool's README.

This is NOT the official Wordle answer or guess list (that list belongs to The New York Times
and is not bundled); it is a general list of common English words of five letters.

Filter: lowercase ASCII words of exactly five letters (no proper nouns, abbreviations or
possessives). One word per line.

Usage: python3 tools/catalog/data/wordle_helper.py
"""
import pathlib
import re
import urllib.request

URL = ("https://app.aspell.net/create?max_size=35&spelling=US&max_variant=0&diacritic=strip"
       "&download=wordlist&encoding=utf-8&format=inline")
FETCHED = "2026-10-18"
LIMIT = 256 * 1024


def main():
    request = urllib.request.Request(URL, headers={"User-Agent": "AXLR-catalog data generator"})
    with urllib.request.urlopen(request, timeout=120) as response:
        text = response.read().decode("utf-8")
    header, _, body = text.partition("\n---\n")
    if "Kevin Atkinson" not in header or "Permission to use" not in header:
        raise RuntimeError("the licence notice was not found in the response")
    words = sorted({w for w in body.split() if re.fullmatch(r"[a-z]{5}", w)})
    lines = ["# Five-letter English words for wordle_helper, generated by tools/catalog/data/wordle_helper.py",
             f"# from {URL}",
             f"# fetched {FETCHED}; filter: lowercase a-z only, exactly 5 letters; {len(words)} words",
             "# Not the official Wordle list. The notice of the source follows, as its licence requires.", "#"]
    lines += ["# " + line if line else "#" for line in header.strip().splitlines()]
    out = pathlib.Path(__file__).resolve().parents[3] / "catalog/tools/personal/wordle_helper/words5.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    content = "\n".join(lines + words) + "\n"
    if len(content.encode()) > LIMIT:
        raise RuntimeError(f"{len(content.encode())} bytes is over the 256 KiB limit")
    out.write_text(content)
    print(f"{out}: {len(words)} words, {len(content.encode())} bytes")


if __name__ == "__main__":
    main()
