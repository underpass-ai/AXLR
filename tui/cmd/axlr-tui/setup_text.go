func (w *setupWizard) t(key string, args ...any) string {
	text, ok := setupText[w.lang][key]
	if !ok {
		text = setupText["en"][key]
	}
	if len(args) == 0 {
		return text
	}
	return fmt.Sprintf(text, args...)
}
