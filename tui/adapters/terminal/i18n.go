// Locale controls interface copy only. Session content, tool output, IDs and
// persisted data are never passed through the translator.
type Locale string

const (
	English Locale = "en"
	Spanish Locale = "es"
)

func ParseLocale(value string) (Locale, error) {
	value = strings.ToLower(strings.TrimSpace(value))
	value = strings.SplitN(value, ".", 2)[0]
	value = strings.ReplaceAll(value, "_", "-")
	switch value {
	case "", "en", "en-us", "en-gb":
		return English, nil
	case "es", "es-es", "es-mx", "es-ar":
		return Spanish, nil
	default:
		if strings.HasPrefix(value, "en-") {
			return English, nil
		}
		if strings.HasPrefix(value, "es-") {
			return Spanish, nil
		}
		return "", fmt.Errorf("unsupported language %q (use en or es)", value)
	}
}

func Translate(locale Locale, label string) string {
	if locale == Spanish {
		if translated, ok := esMessages[label]; ok {
			return translated
		}
	}
	if english, ok := enMessages[label]; ok {
		return english
	}
	return label
}

func Translatef(locale Locale, label string, args ...any) string {
	return fmt.Sprintf(Translate(locale, label), args...)
}

func (t Theme) T(label string) string               { return Translate(t.Locale, label) }
func (t Theme) Tf(label string, args ...any) string { return Translatef(t.Locale, label, args...) }

